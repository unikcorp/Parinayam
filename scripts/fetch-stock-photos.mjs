// One-time script: searches Unsplash for South Indian portrait and wedding
// photos and bakes the resulting direct image URLs into
// src/lib/stock-photos.ts. Not run at build/runtime — run manually whenever
// the curated set needs refreshing.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ACCESS_KEY = process.env.UNSPLASH_ACCESS_KEY;

if (!ACCESS_KEY) {
  console.error("Missing UNSPLASH_ACCESS_KEY (checked process.env).");
  process.exit(1);
}

async function search(query, { perPage = 15, orientation = "squarish" } = {}) {
  const url = `https://api.unsplash.com/search/photos?query=${encodeURIComponent(
    query
  )}&per_page=${perPage}&orientation=${orientation}`;
  const res = await fetch(url, {
    headers: { Authorization: `Client-ID ${ACCESS_KEY}` },
  });
  if (!res.ok) {
    throw new Error(`Unsplash error ${res.status}: ${await res.text()}`);
  }
  const data = await res.json();
  console.log(`  "${query}" → ${data.results.length} results (of ${data.total} total)`);
  return data.results
    .filter((r) => r.urls?.regular && r.urls?.small)
    .map((r) => ({
      id: r.id,
      regular: r.urls.regular,
      small: r.urls.small,
      alt: r.alt_description ?? query,
    }));
}

console.log("Fetching curated South Indian stock photos from Unsplash...");

const [menPortraits, womenPortraits, couples, weddings] = await Promise.all([
  search("south indian man portrait", { orientation: "squarish", perPage: 15 }),
  search("south indian woman portrait", { orientation: "squarish", perPage: 15 }),
  search("south indian wedding couple", { orientation: "landscape", perPage: 15 }),
  search("kerala bride groom", { orientation: "landscape", perPage: 10 }),
]);

// de-dupe by id across the two "photo" sets (couples/weddings overlap in theme)
const seen = new Set();
const photos = [...couples, ...weddings].filter((p) => {
  if (seen.has(p.id)) return false;
  seen.add(p.id);
  return true;
});

const menSeen = new Set();
const men = menPortraits.filter((p) => (menSeen.has(p.id) ? false : menSeen.add(p.id)));
const womenSeen = new Set();
const women = womenPortraits.filter((p) => (womenSeen.has(p.id) ? false : womenSeen.add(p.id)));

const out = `// Auto-generated by scripts/fetch-stock-photos.mjs — do not hand-edit.
// Curated South Indian portrait & wedding photos from Unsplash (free license,
// hotlink-safe CDN URLs). Regenerate with:
//   UNSPLASH_ACCESS_KEY=... node scripts/fetch-stock-photos.mjs

export interface StockPhoto {
  id: string;
  regular: string;
  small: string;
  alt: string;
}

export const avatarPhotos: { men: StockPhoto[]; women: StockPhoto[] } = ${JSON.stringify(
  { men, women },
  null,
  2
)};

export const scenePhotos: StockPhoto[] = ${JSON.stringify(photos, null, 2)};
`;

const outPath = path.join(__dirname, "..", "src", "lib", "stock-photos.ts");
fs.writeFileSync(outPath, out);
console.log(`\nWrote ${men.length} male + ${women.length} female portraits and ${photos.length} scene photos to ${outPath}`);
